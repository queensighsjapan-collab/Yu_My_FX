// Generates Source/Tables.inc (parameter list, option list, factory presets) from yumy-bacteria.html.
// usage: node tools/gen_tables.js /path/to/yumy-bacteria.html > Source/Tables.inc
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');
const a = src.indexOf('const S={OFF:0');
const b = src.indexOf('// ---------- messaging');
const code = src.slice(a, b).replace(/let FACTORY=0;/, '');
const OPT_KEYS = ['vbands','uni','osc2mode','l1s','l2s','l3s','l1k','l2k','l3k','mono','osc1mode','sync','ring','f1mode','f2mode','routing','arp','ahold','amode','ares','alen','apat','cmode','dsync','rsize'];
const { INIT, OINIT, PRESETS } = new Function(code + '; return {INIT,OINIT,PRESETS};')();
const id = n => n.replace(/[^A-Za-z0-9]+/g, '_');
let o = '// GENERATED by tools/gen_tables.js from yumy-bacteria.html - do not edit by hand\n';
o += '#define YB_PARAM_LIST(X) \\\n' + Object.keys(INIT).map(n => `  X(${id(n)}, "${n}", ${INIT[n]})`).join(' \\\n') + '\n';
o += '#define YB_OPT_LIST(X) \\\n' + OPT_KEYS.map(k => `  X(${k}, ${OINIT[k]})`).join(' \\\n') + '\n';
const names = Object.keys(INIT);
const pre = PRESETS.slice(0).filter(p => p.name !== undefined);
o += `#define YB_NUM_FACTORY ${pre.length}\n`;
o += 'static const struct FactoryPreset { const char* name; int k[' + names.length + ']; int o[' + OPT_KEYS.length + ']; int ld[3]; int mx[6][7]; } kFactory[] = {\n';
for (const p of pre) {
  const k = names.map(n => (p.k && n in p.k) ? p.k[n] : INIT[n]);
  const oo = Object.assign({}, OINIT, p.o || {});
  const ov = OPT_KEYS.map(x => oo[x]);
  const ld = (oo.ld || [0, 0, 0]);
  const mx = [];
  for (let i = 0; i < 6; i++) {
    const sl = p.mx && p.mx[i];
    const d = [0, 0, 0], am = [0, 0, 0];
    for (let j = 0; j < 3; j++) { const e = (sl && sl[1 + j]) || [0, 0]; d[j] = e[0]; am[j] = e[1]; }
    mx.push([sl ? sl[0] : 0, ...d, ...am]);
  }
  o += `  {"${p.name}",{${k.join(',')}},{${ov.join(',')}},{${ld.join(',')}},{${mx.map(r => '{' + r.join(',') + '}').join(',')}}},\n`;
}
o += '};\n';
process.stdout.write(o);
